export const TYPESET_FONT_GROUPS = [
	{ label: 'Sans', fonts: TYPESET_FONTS.filter((font) => font.type === 'sans') },
	{ label: 'Serif', fonts: TYPESET_FONTS.filter((font) => font.type === 'serif') },
	{ label: 'Mono', fonts: TYPESET_FONTS.filter((font) => font.type === 'mono') },
] as const;

const FONT_MAP = new Map(TYPESET_FONTS.map((font) => [font.id, font]));

export function findTypesetFont(id: string | null | undefined): TypesetFont | undefined {
	return id ? FONT_MAP.get(id) : undefined;
}

export function typesetFontFamily(id: string): string {
	const font = findTypesetFont(id) ?? TYPESET_FONTS[0];
	return `'${font.previewFamily}', ${font.type === 'mono' ? 'monospace' : font.type === 'serif' ? 'serif' : 'sans-serif'}`;
}
