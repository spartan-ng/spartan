import type { MigrateCnGeneratorSchema } from './schema';

/**
 * Fingerprints (see {@link sourceFingerprint}) of every `hlm.ts` the CLI has generated so far.
 * A file matching one of them was not customized and can safely be replaced by the new template.
 */
const KNOWN_HLM_FINGERPRINTS = new Set([
	// hlm only, `import { clsx, type ClassValue } from 'clsx'`
	'2d57421d38be8edd1c033c431e073cc73fb09d2cbbf0a37053b4e354b2a5f6bd',
	// hlm only, `import { type ClassValue, clsx } from 'clsx'`
	'2e39512afda3a1a2006011f1d21cd6e118dc754a5606b8b9be0598745f045a2a',
	// hlm + classes, merging with `twMerge(clsx(...))`
	'72e21ba3543787143fb1edd5508f971f1036668d0d32641fb680d30bcf24991f',
	// hlm + classes, merging with `hlm(...)`
	'b9ea9748abd02fe5e61239f3453b0d60db9f28ca23be9bc2efd4daf7e27dda6f',
	// hlm + classes with transition suppression
	'18e0afa92823d08cb15dff6c71abdb258b09737dded10e63e36065548ee2003d',
	// hlm + classes with the mutation observer created outside the angular zone
	'855e11e213e039adba038ef1d445d4dbe455ac8129ec14d8314b0d3458cc01a0',
]);

/** Where each named export of `tailwind-merge` lives in `cn`, and under which name. */
const TAILWIND_MERGE_EXPORTS: Record<string, { module: 'cn' | 'cn/config'; name: string }> = {
	twMerge: { module: 'cn', name: 'twMerge' },
	twJoin: { module: 'cn', name: 'twJoin' },
	ClassNameValue: { module: 'cn', name: 'ClassNameValue' },
	extendTailwindMerge: { module: 'cn/config', name: 'extendTailwindMerge' },
	createTailwindMerge: { module: 'cn/config', name: 'createTwMerge' },
	getDefaultConfig: { module: 'cn/config', name: 'defaultConfig' },
	fromTheme: { module: 'cn/config', name: 'fromTheme' },
	validators: { module: 'cn/config', name: 'validators' },
	mergeConfigs: { module: 'cn/config', name: 'mergeConfigs' },
};

const NAMED_IMPORT_REGEX = /import\s+(type\s+)?{([^}]*)}\s*from\s*['"](clsx|clsx\/lite|tailwind-merge)['"];?/g;
const DEFAULT_CLSX_IMPORT_REGEX = /import\s+(\w+)\s+from\s*['"](clsx|clsx\/lite)['"];?/g;
const REMAINING_IMPORT_REGEX = /from\s*['"](clsx|clsx\/lite|tailwind-merge)['"]/;

export async function migrateCnGenerator(
	tree: Tree,
	{ skipFormat }: MigrateCnGeneratorSchema,
): Promise<GeneratorCallback | undefined> {
	const remainingImports = migrateFiles(tree);
	const installTask = updateDependencies(tree, remainingImports);

	if (!skipFormat) {
		await formatFiles(tree);
	}

	return installTask;
}

/**
 * Replaces the `hlm.ts` files generated by the CLI with the new template and rewrites every other
 * `clsx` / `tailwind-merge` import to `cn`. Returns the files that still import one of them.
 */
function migrateFiles(tree: Tree): string[] {
	const hlmTemplate = readFileSync(
		join(__dirname, '..', 'ui', 'libs', 'utils', 'files', 'lib', 'hlm.ts.template'),
		'utf-8',
	);
	const remainingImports: string[] = [];

	visitFiles(tree, '.', (path) => {
		if (!path.endsWith('.ts') || path.includes('node_modules')) return;

		const content = tree.read(path, 'utf-8');
		if (!content || !REMAINING_IMPORT_REGEX.test(content)) return;

		if (KNOWN_HLM_FINGERPRINTS.has(sourceFingerprint(content))) {
			tree.write(path, hlmTemplate);
			return;
		}

		const migrated = replaceImports(content, path);
		tree.write(path, migrated);

		if (REMAINING_IMPORT_REGEX.test(migrated)) {
			remainingImports.push(path);
			logger.warn(
				`[migrate-cn] ${path} still imports from 'clsx' or 'tailwind-merge' (unsupported import). Please migrate it to 'cn' manually.`,
			);
		}

		if (/export\s+(function|const)\s+hlm\b/.test(content)) {
			logger.warn(
				`[migrate-cn] ${path} is a customized hlm.ts. Its imports were migrated to 'cn', but its classes() ` +
					`implementation was kept. To use the shared implementation, replace it with ` +
					`\`brnClasses(computed, { ...options, merge: hlm })\` from '@spartan-ng/brain/core'.`,
			);
		}
	});

	return remainingImports;
}

function replaceImports(content: string, path: string): string {
	return content
		.replace(DEFAULT_CLSX_IMPORT_REGEX, (_match, name: string, module: string) => {
			const target = module === 'clsx' ? 'cn' : 'cn/lite';
			return name === 'clsx' ? `import { clsx } from '${target}';` : `import { clsx as ${name} } from '${target}';`;
		})
		.replace(NAMED_IMPORT_REGEX, (match, typeOnly: string | undefined, specifiers: string, module: string) => {
			if (module !== 'tailwind-merge') {
				return `import ${typeOnly ?? ''}{${specifiers}} from '${module === 'clsx' ? 'cn' : 'cn/lite'}';`;
			}

			const byModule = new Map<string, string[]>();
			const unsupported: string[] = [];

			for (const specifier of specifiers
				.split(',')
				.map((s) => s.trim())
				.filter(Boolean)) {
				const isType = specifier.startsWith('type ');
				const [name, alias] = specifier
					.replace(/^type\s+/, '')
					.split(/\s+as\s+/)
					.map((s) => s.trim());
				const target = TAILWIND_MERGE_EXPORTS[name];

				if (!target) {
					unsupported.push(specifier);
					continue;
				}

				const localName = alias ?? name;
				const imported = target.name === localName ? localName : `${target.name} as ${localName}`;
				const list = byModule.get(target.module) ?? [];
				list.push(isType ? `type ${imported}` : imported);
				byModule.set(target.module, list);
			}

			const imports = [...byModule]
				.sort(([a], [b]) => a.localeCompare(b))
				.map(([target, names]) => `import ${typeOnly ?? ''}{ ${names.join(', ')} } from '${target}';`);

			if (unsupported.length > 0) {
				logger.warn(`[migrate-cn] ${path}: ${unsupported.join(', ')} has no equivalent in 'cn'.`);
				imports.push(`import ${typeOnly ?? ''}{ ${unsupported.join(', ')} } from 'tailwind-merge';`);
			}

			return imports.length > 0 ? imports.join('\n') : match;
		});
}

function updateDependencies(tree: Tree, remainingImports: string[]): GeneratorCallback | undefined {
	if (!tree.exists('package.json')) return undefined;

	const dependencies: Record<string, string> = { cn: CN_VERSION };

	// the new hlm.ts imports brnClasses, which requires a brain version released with this migration
	const cliVersion = getCliPackageVersion();
	const brainVersion = getInstalledPackageVersion(tree, '@spartan-ng/brain');
	if (brainVersion && lt(brainVersion, cliVersion)) {
		dependencies['@spartan-ng/brain'] = cliVersion;
	}

	const packageJson = readJson(tree, 'package.json');
	const isDevDependency = (name: string) => !packageJson.dependencies?.[name] && !!packageJson.devDependencies?.[name];

	if (remainingImports.length === 0) {
		const unused = ['clsx', 'tailwind-merge'];
		removeDependenciesFromPackageJson(
			tree,
			unused.filter((name) => !isDevDependency(name)),
			unused.filter(isDevDependency),
		);
	}

	return addDependenciesToPackageJson(tree, dependencies, {});
}

export default migrateCnGenerator;
